"""Author the scrub-nurse theatre layer and the stages that use it (pure USD, no Isaac needed):

    uv run --no-project --with usd-core --with pyyaml python g1-isaac-sim/make_theatre_layer.py
    (or: ./g1-isaac-sim/run.sh --stage, which runs make_stage.py and then this)

Reads hospital-sim-env/objects/placements.yaml (the single source of object poses, shared with MuJoCo) and
hospital-sim-env/objects/catalog.json.
Writes
  g1-isaac-sim/usd/theatre_instruments.usd   /World/Theatre/<name>: references to hospital-sim-env/objects/usd/<name>.usd at the
                                          world poses; `over`s that deactivate `remove_scene_props` (OR-suite
                                          prims and their HG1 collider boxes)
  g1-isaac-sim/usd/hospital_g1_theatre.usd   root = theatre_instruments.usd + hospital_g1_robot.usd
  g1-isaac-sim/usd/flat_theatre_robot.usd    root = theatre_instruments.usd + flat_g1_robot.usd + a ground slab under
                                          the theatre objects (quick physics tests without the hospital)
Every prim under /World/Theatre carries customData hg1:type (instrument | furniture | person | site), which
run_sim.py uses for /sim/objects.
"""
from __future__ import annotations

import json
import math
import os

import yaml
from pxr import Gf, Sdf, Usd, UsdGeom, UsdPhysics

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
USD_DIR = os.path.join(HERE, "usd")
OBJ = os.path.join(REPO, "hospital-sim-env", "objects")
LAYER = os.path.join(USD_DIR, "theatre_instruments.usd")


def new_layer(path):
    layer = Sdf.Layer.FindOrOpen(path) if os.path.exists(path) else Sdf.Layer.CreateNew(path)
    layer.Clear()
    return layer


def main():
    pl = yaml.safe_load(open(os.path.join(OBJ, "placements.yaml")))
    cat = json.load(open(os.path.join(OBJ, "catalog.json")))
    poses = cat["world_poses"]
    layer = new_layer(LAYER)
    st = Usd.Stage.Open(layer)
    UsdGeom.SetStageUpAxis(st, UsdGeom.Tokens.z)
    UsdGeom.SetStageMetersPerUnit(st, 1.0)
    st.OverridePrim("/World")
    UsdGeom.Scope.Define(st, "/World/Theatre")
    kinds = {n: "instrument" for n in cat["instruments"]}
    kinds.update(instrument_table="furniture", tool_rack="furniture", surgeon="person")
    for name, kind in kinds.items():
        x = UsdGeom.Xform.Define(st, f"/World/Theatre/{name}")
        x.GetPrim().GetReferences().AddReference(os.path.relpath(os.path.join(OBJ, "usd", f"{name}.usd"), USD_DIR))
        p, q = poses[name]["pos"], poses[name]["quat"]
        x.AddTranslateOp(UsdGeom.XformOp.PrecisionDouble).Set(Gf.Vec3d(*p))
        x.AddOrientOp(UsdGeom.XformOp.PrecisionDouble).Set(Gf.Quatd(q[0], *q[1:]))
        x.GetPrim().SetCustomDataByKey("hg1:type", kind)
        x.GetPrim().SetCustomDataByKey("hg1:name", name)
    # the hand site lives inside surgeon.usd (/surgeon/surgeon_hand); tag it for /sim/objects
    hp = st.OverridePrim("/World/Theatre/surgeon/surgeon_hand")
    hp.SetCustomDataByKey("hg1:type", "site")
    hp.SetCustomDataByKey("hg1:name", "surgeon_hand")
    # scene props in the surgeon's spot: deactivate the prop and its collider box (make_stage.py naming)
    for prop in pl.get("remove_scene_props", []):
        for path in (f"/World/Wing/ORSuite/Props/{prop}", f"/World/HG1_Colliders/Furniture/{prop}"):
            st.OverridePrim(path).SetActive(False)
    layer.documentation = "Scrub-nurse theatre objects. Generated by g1-isaac-sim/make_theatre_layer.py from hospital-sim-env/objects/placements.yaml."
    layer.Save()

    root = new_layer(os.path.join(USD_DIR, "hospital_g1_theatre.usd"))
    root.subLayerPaths.append("./theatre_instruments.usd")
    root.subLayerPaths.append("./hospital_g1_robot.usd")
    rs = Usd.Stage.Open(root)
    UsdGeom.SetStageUpAxis(rs, UsdGeom.Tokens.z)
    UsdGeom.SetStageMetersPerUnit(rs, 1.0)
    root.documentation = "Hospital + G1 + scrub-nurse theatre objects. Generated by g1-isaac-sim/make_theatre_layer.py."
    root.Save()

    flat = new_layer(os.path.join(USD_DIR, "flat_theatre_robot.usd"))
    flat.subLayerPaths.append("./theatre_instruments.usd")
    flat.subLayerPaths.append("./flat_g1_robot.usd")
    fs = Usd.Stage.Open(flat)
    UsdGeom.SetStageUpAxis(fs, UsdGeom.Tokens.z)
    UsdGeom.SetStageMetersPerUnit(fs, 1.0)
    tx, ty = poses["instrument_table"]["pos"][:2]
    g = UsdGeom.Cube.Define(fs, "/World/TheatreGround")
    g.CreateSizeAttr(1.0)
    g.CreateDisplayColorAttr([(0.55, 0.57, 0.6)])
    xf = UsdGeom.Xformable(g)
    xf.AddTranslateOp().Set(Gf.Vec3d(tx - 1.0, ty + 1.0, -0.05))
    xf.AddScaleOp().Set(Gf.Vec3d(8, 8, 0.1))
    UsdPhysics.CollisionAPI.Apply(g.GetPrim())
    flat.documentation = "Flat test stage with the theatre objects. Generated by g1-isaac-sim/make_theatre_layer.py."
    flat.Save()
    n_rm = len(pl.get("remove_scene_props", []))
    print(f"theatre layer: {len(kinds)} objects, {n_rm} scene props deactivated -> {LAYER}")
    print("stages: usd/hospital_g1_theatre.usd, usd/flat_theatre_robot.usd")


if __name__ == "__main__":
    main()
